// labels are the sections of the header of a record type, in order.
var labels = []string{"Identity", "States", "Transitions", "Invariants", "Persistence", "Locks and waits"}

// header is the doc comment of a record type split into its sections.
type header struct {
	purpose  []string
	sections map[string]string
}

// render returns docs/memory/cxl/states.md for the record types whose Go
// files are in the directory stateDir and the kernel objects whose Go files
// are in the directory kernelDir.
func render(stateDir, kernelDir string) ([]byte, error) {
	docs, triggers, err := parseState(stateDir)
	if err != nil {
		return nil, err
	}
	kernelDocs, err := parseKernel(kernelDir)
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("# CXL driver states\n\n")
	b.WriteString("<!-- Generated by go generate in cmd/plugins/dra-driver-cxl from internal/state and pkg/cxl/kernel. Do not edit. -->\n\n")
	b.WriteString("The records that the CXL DRA driver keeps in its store, `state.json` in the plugin data\n")
	b.WriteString("directory of `cxl.nri.io`, and the transitions of every state field; `Memdev.Busy` is held in\n")
	b.WriteString("memory only. The driver refuses a transition that is not a row of its table. In the effects,\n")
	b.WriteString("\"commit (d)\" is durable before the next externally visible act, \"commit (l)\" is lazy. The\n")
	b.WriteString("last part, \"Kernel objects\", has the states of the CXL kernel objects that the driver observes.\n\n")
	b.WriteString("Triggers:\n\n")
	for _, tr := range state.Triggers {
		fmt.Fprintf(&b, "- `%s`: %s\n", tr, escape(triggers[string(tr)]))
	}
	b.WriteString("\n")
	for _, o := range state.Catalogue() {
		h, ok := docs[o.Name]
		if !ok {
			return nil, fmt.Errorf("%s: no doc comment of type %s", stateDir, o.Name)
		}
		fmt.Fprintf(&b, "## %s\n\n", o.Name)
		for _, p := range h.purpose {
			b.WriteString(escape(p) + "\n\n")
		}
		for _, l := range labels {
			fmt.Fprintf(&b, "**%s.** %s\n\n", l, escape(capitalize(h.sections[l])))
			if l == "Transitions" {
				for _, t := range o.Tables {
					renderTable(&b, t)
				}
			}
		}
	}
	b.WriteString("## Invariants over the document\n\n")
	b.WriteString("Checked by `state.Check` over the records alone; the engine checks the invariants that also\n")
	b.WriteString("need the kernel's view.\n\n")
	for _, inv := range state.DocumentInvariants {
		fmt.Fprintf(&b, "- **%s**: %s\n", inv.Name, escape(inv.Text))
	}
	if err := renderKernel(&b, kernelDocs, kernelDir); err != nil {
		return nil, err
	}
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n'), nil
}

// renderKernel writes the sections of the kernel objects: the header of
// each and the tables of its states.
func renderKernel(b *bytes.Buffer, docs map[string][]kernelParagraph, kernelDir string) error {
	b.WriteString("\n## Kernel objects\n\n")
	b.WriteString("The CXL kernel objects of the node as package `pkg/cxl/kernel` observes them. Their states are the\n")
	b.WriteString("kernel's: they are observed, never applied, and an unchanged state is no transition. The rows are\n")
	b.WriteString("the changes that the operations of the package and the kernel's events make, also those that one\n")
	b.WriteString("operation makes between two observations; the engine logs an observed change that is not a row of\n")
	b.WriteString("its table at debug level (\"kernel transition not in table\").\n\n")
	for _, o := range kernel.Catalogue() {
		h, ok := docs[o.Name]
		if !ok {
			return fmt.Errorf("%s: no header comment of %s", kernelDir, o.Name)
		}
		fmt.Fprintf(b, "## %s (kernel)\n\n", o.Name)
		for _, p := range h {
			if p.label != "" {
				fmt.Fprintf(b, "**%s.** %s\n\n", p.label, escapeText(capitalize(p.text)))
				continue
			}
			b.WriteString(escapeText(p.text) + "\n\n")
		}
		for _, t := range o.Tables {
			renderTable(b, t)
		}
	}
	return nil
}

// renderTable writes a transition table as a markdown table.
func renderTable(b *bytes.Buffer, t state.TableText) {
	fmt.Fprintf(b, "### %s.%s\n\n", t.Object, t.Field)
	fmt.Fprintf(b, "States: %s.\n\n", strings.Join(t.States, ", "))
	b.WriteString("| from | to | trigger | guard | effects |\n")
	b.WriteString("|:-----|:---|:--------|:------|:--------|\n")
	for _, r := range t.Rows {
		to := "(unchanged)"
		if !r.Stays {
			to = strings.Join(r.To, ", ")
		}
		trigger := ""
		if len(r.Triggers) > 0 {
			trigger = "`" + strings.Join(r.Triggers, "`, `") + "`"
		}
		switch {
		case trigger != "" && r.When != "":
			trigger += ": " + escape(r.When)
		case r.When != "":
			trigger = escape(r.When)
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			strings.Join(r.From, ", "), to, cell(trigger), cell(escape(r.Guard)), cell(escape(r.Effects)))
	}
	b.WriteString("\n")
	if len(t.Refused) > 0 {
		b.WriteString("Refused:\n\n")
		for _, r := range t.Refused {
			fmt.Fprintf(b, "- %s\n", escape(r))
		}
		b.WriteString("\n")
	}
}

// kernelLabel matches the label of a section of the header comment of a
// kernel object at the start of a line.
var kernelLabel = regexp.MustCompile(`^(Identity|Facts|States|State|Transitions|Invariants|Waits|Hidden kernel state|Kernel rule)( \([A-Za-z]+\))?: `)

// parseKernel returns the header comments of the kernel objects in the Go
// files of the directory dir, by the name that starts each, as paragraphs:
// the purpose and one per labelled section.
func parseKernel(dir string) (map[string][]kernelParagraph, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(names)
	docs := map[string][]kernelParagraph{}
	fset := token.NewFileSet()
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, cg := range f.Comments {
			text := cg.Text()
			first, _, _ := strings.Cut(text, "\n")
			object, _, ok := strings.Cut(first, ": ")
			if !ok || !kernelObjectName(object) {
				continue
			}
			if _, dup := docs[object]; dup {
				return nil, fmt.Errorf("%s: a second header comment of %s", name, object)
			}
			docs[object] = kernelParagraphs(text)
		}
	}
	return docs, nil
}

// kernelObjectName tells whether text is the name of a kind of kernel
// object of the catalogue.
func kernelObjectName(text string) bool {
	for _, o := range kernel.Catalogue() {
		if o.Name == text {
			return true
		}
	}
	return false
}

// kernelParagraph is a paragraph of the header comment of a kernel object:
// the purpose (no label) or a labelled section.
type kernelParagraph struct {
	label, text string
}

// kernelParagraphs returns the header comment text as paragraphs: the
// purpose, then a paragraph per labelled section.
func kernelParagraphs(text string) []kernelParagraph {
	var (
		out   []kernelParagraph
		cur   *kernelParagraph
		flush = func() {
			if cur != nil {
				cur.text = strings.TrimSpace(cur.text)
				out = append(out, *cur)
				cur = nil
			}
		}
	)
	for _, line := range strings.Split(text, "\n") {
		line = strings.TrimSpace(line)
		switch {
		case line == "":
			flush()
		case kernelLabel.MatchString(line):
			flush()
			label, rest, _ := strings.Cut(line, ": ")
			cur = &kernelParagraph{label: label, text: rest}
		case cur == nil:
			cur = &kernelParagraph{text: line}
		default:
			cur.text += " " + line
		}
	}
	flush()
	return out
}

// cell returns the text of a table cell: "-" for none.
func cell(text string) string {
	if text == "" {
		return "-"
	}
	return text
}

// escapeText returns the text of a paragraph with the characters that
// markdown would take as markup escaped.
func escapeText(text string) string {
	r := strings.NewReplacer("*", `\*`, "<", "&lt;")
	return r.Replace(text)
}

// escape returns the text of a table cell with the characters that
// markdown would take as markup escaped.
func escape(text string) string {
	r := strings.NewReplacer("|", `\|`, "*", `\*`, "<", "&lt;")
	return r.Replace(text)
}

// parseState returns the headers of the record types and the doc comments
// of the triggers in the Go files of the directory dir.
func parseState(dir string) (map[string]header, map[string]string, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, nil, err
	}
	sort.Strings(names)
	docs := map[string]header{}
	triggers := map[string]string{}
	fset := token.NewFileSet()
	for _, name := range names {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, name, nil, parser.ParseComments)
		if err != nil {
			return nil, nil, err
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gd.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					typeHeader(gd, s, docs)
				case *ast.ValueSpec:
					if err := triggerDoc(s, triggers); err != nil {
						return nil, nil, err
					}
				}
			}
		}
	}
	return docs, triggers, nil
}

// typeHeader adds the header of a record type to docs: a type whose doc
// comment has an Identity section.
func typeHeader(gd *ast.GenDecl, s *ast.TypeSpec, docs map[string]header) {
	doc := s.Doc
	if doc == nil && len(gd.Specs) == 1 {
		doc = gd.Doc
	}
	if doc != nil && strings.Contains(doc.Text(), "\nIdentity: ") {
		docs[s.Name.Name] = splitHeader(doc.Text())
	}
}

// triggerDoc adds the doc comment of a Trigger constant to triggers by its
// value.
func triggerDoc(s *ast.ValueSpec, triggers map[string]string) error {
	if s.Doc == nil || len(s.Values) != 1 {
		return nil
	}
	if id, ok := s.Type.(*ast.Ident); !ok || id.Name != "Trigger" {
		return nil
	}
	lit, ok := s.Values[0].(*ast.BasicLit)
	if !ok {
		return nil
	}
	v, err := strconv.Unquote(lit.Value)
	if err != nil {
		return err
	}
	triggers[v] = strings.TrimPrefix(paragraph(s.Doc.Text()), s.Names[0].Name+" is ")
	return nil
}

// splitHeader returns the doc comment text split into the purpose and the
// labelled sections.
func splitHeader(text string) header {
	h := header{sections: map[string]string{}}
	for _, p := range strings.Split(strings.TrimSpace(text), "\n\n") {
		p = paragraph(p)
		label := ""
		for _, l := range labels {
			if strings.HasPrefix(p, l+": ") {
				label = l
			}
		}
		if label == "" {
			h.purpose = append(h.purpose, p)
			continue
		}
		h.sections[label] = strings.TrimPrefix(p, label+": ")
	}
	return h
}

// capitalize returns text with its first letter in upper case.
func capitalize(text string) string {
	if text == "" {
		return text
	}
	return strings.ToUpper(text[:1]) + text[1:]
}

// paragraph returns the lines of a paragraph joined into one.
func paragraph(text string) string {
	return strings.Join(strings.Fields(text), " ")
}
