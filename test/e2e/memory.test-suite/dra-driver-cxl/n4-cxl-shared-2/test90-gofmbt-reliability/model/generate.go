package main

// The off-line mode (04-contract.txt 5): a code.gen.sh of mbt-step and
// mbt-expect lines. Without the observations nothing is adopted: the
// "any" slots are left out of the profile, and what a race leaves open
// (the outcome of a controller kill, steering in a driver restart
// window, data that was never written) stays open in the expectations
// until an event decides it. The planner gets no deadline, so the same
// seed and flags give the same script.

import (
	"encoding/json"
	"fmt"
	"io"
	"strings"
)

// generate writes a code.gen.sh to w: planned steps, or with from the
// steps of a steps file (with the adoption records of an on-line run,
// whose outcomes the following expectations then follow).
func generate(o runOpts, from []stepLine, w io.Writer) error {
	mm := newMbtModel(o.cfg)
	pl, err := newPlanner(mm, o.cov, o.depth, o.seed, o.randomness)
	if err != nil {
		return err
	}
	st := newState(o.cfg)
	fmt.Fprintf(w, "# code.gen.sh: generated by mbt-cxl generate (gofmbt %s)\n# %s\n", gofmbtVersion, o.header)
	fmt.Fprintf(w, "# profile %s (%d slots), seed %d, depth %d, coverage %s\n", o.cfg.Profile, len(o.cfg.Slots), o.seed, o.depth, o.cov)
	// emit writes a step and its expectation (A14: every step has one)
	// and returns the state after it.
	emit := func(a Act, final bool) (*State, error) {
		next := st.apply(a)
		n := int(next.Steps)
		name := a.name(o.cfg)
		fmt.Fprintf(w, "mbt-step %d %s\n", n, name)
		var exp *Expectation
		if a.Verb == VSettle {
			exp = next.expect(n, name)
			exp.Final = final
		} else {
			exp = expectDone(st, next, a, n)
		}
		js, err := json.Marshal(exp)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(w, "mbt-expect %d <<'EOF'\n%s\nEOF\n", n, js)
		pl.mark(st, a, next)
		return next, nil
	}
	settle := Act{Verb: VSettle, Slot: -1, VM: VMAny, Pool: noPool}
	if from == nil {
		if st, err = emit(settle, false); err != nil {
			return err
		}
		for o.maxSteps <= 0 || int(st.Steps)-1 < o.maxSteps {
			a, _ := pl.plan(st, planBudget{MaxPaths: o.maxPaths})
			if !st.enabled(a) {
				break
			}
			if st, err = emit(a, false); err != nil {
				return err
			}
		}
	} else {
		for j, line := range from {
			a, err := parseAct(o.cfg, line.Action)
			if err != nil {
				return fmt.Errorf("--from: line %d: %w", j+1, err)
			}
			if !st.allowed(a) {
				return fmt.Errorf("--from: step %d %q is not enabled in the model state", st.Steps+1, line.Action)
			}
			final := a.Verb == VSettle && j == len(from)-1 && allAbsent(st)
			next, err := emit(a, final)
			if err != nil {
				return err
			}
			switch {
			case line.Has:
				if next, err = applyAdoption(next, line.Adopt); err != nil {
					return fmt.Errorf("--from: step %d: %w", next.Steps, err)
				}
			case a.Verb == VSettle:
				if open := next.openChoice(); open != "" {
					return fmt.Errorf("--from: step %d settle leaves %s open, and the steps file has no adoption record of it (\"#adopt %d ...\", written by on-line runs since R5): the expectations after it would not follow the run", next.Steps, open, next.Steps)
				}
			}
			st = next
		}
		if allAbsent(st) && st.Unsettled == 0 {
			return nil
		}
	}
	tear := teardownActs(st)
	for j, a := range tear {
		if st, err = emit(a, j == len(tear)-1); err != nil {
			return err
		}
	}
	return nil
}

// stepLines makes step lines of plain actions.
func stepLines(acts []string) []stepLine {
	out := make([]stepLine, 0, len(acts))
	for _, a := range acts {
		out = append(out, stepLine{Action: a})
	}
	return out
}

// allAbsent: no slot has a pod, and nothing is in flight but deletes.
func allAbsent(s *State) bool {
	for i := range s.Slots {
		if ph := s.Slots[i].Phase; ph != Absent && ph != Deleting {
			return false
		}
	}
	for p := range s.Ctrl {
		if !s.Ctrl[p].Up {
			return false
		}
	}
	return true
}

// genScript is a parsed code.gen.sh.
type genScript struct {
	Steps   []string             // action of step n at index n-1
	Expects map[int]*Expectation // expectations by step
}

// parseGenScript parses a code.gen.sh (for tests and --from checks).
func parseGenScript(text string) (*genScript, error) {
	g := &genScript{Expects: map[int]*Expectation{}}
	lines := strings.Split(text, "\n")
	for j := 0; j < len(lines); j++ {
		line := lines[j]
		switch {
		case line == "" || strings.HasPrefix(line, "#"):
		case strings.HasPrefix(line, "mbt-step "):
			f := strings.SplitN(line, " ", 3)
			if len(f) != 3 || f[1] != fmt.Sprint(len(g.Steps)+1) {
				return nil, fmt.Errorf("line %d: %q: want mbt-step %d ACTION", j+1, line, len(g.Steps)+1)
			}
			g.Steps = append(g.Steps, f[2])
		case strings.HasPrefix(line, "mbt-expect "):
			var n int
			if _, err := fmt.Sscanf(line, "mbt-expect %d <<'EOF'", &n); err != nil {
				return nil, fmt.Errorf("line %d: %q: %v", j+1, line, err)
			}
			if n != len(g.Steps) {
				return nil, fmt.Errorf("line %d: expectation of step %d after step %d", j+1, n, len(g.Steps))
			}
			var body []string
			for j++; j < len(lines) && lines[j] != "EOF"; j++ {
				body = append(body, lines[j])
			}
			if j >= len(lines) {
				return nil, fmt.Errorf("step %d: unterminated here-document", n)
			}
			e := &Expectation{}
			if err := json.Unmarshal([]byte(strings.Join(body, "\n")), e); err != nil {
				return nil, fmt.Errorf("step %d: %v", n, err)
			}
			if e.Step != n {
				return nil, fmt.Errorf("step %d: expectation of step %d", n, e.Step)
			}
			g.Expects[n] = e
		default:
			return nil, fmt.Errorf("line %d: unexpected %q", j+1, line)
		}
	}
	return g, nil
}
